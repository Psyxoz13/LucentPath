        private static Entry[] _extended;

        private readonly struct Entry
        {
            public readonly int S;
            public readonly uint A;
            public readonly uint[] MInit;

            public Entry(int s, uint a, uint[] mInit)
            {
                S = s;
                A = a;
                MInit = mInit;
            }
        }

        internal static void GetEntry(int d, out int s, out uint a, out ReadOnlySpan<uint> mInit)
        {
            if (d < 1)
            {
                throw new ArgumentOutOfRangeException(nameof(d));
            }

            var table = _extended ?? _builtIn;
            int idx = d - 1;

            if (idx >= table.Length)
            {
                throw new ArgumentOutOfRangeException(nameof(d),
                    $"Joe-Kuo table covers dimensions 1..{table.Length}.");
            }

            var e = table[idx];

            s = e.S;
            a = e.A;
            mInit = e.MInit;
        }

        internal static void LoadExtended(string fileText)
        {
            if (fileText == null)
            {
                throw new ArgumentNullException(nameof(fileText));
            }

            var list = new List<Entry>(2048) { _builtIn[0] };

            int expectedD = 2;

            using (var reader = new StringReader(fileText))
            {
                string line;
                bool firstLine = true;

                while ((line = reader.ReadLine()) != null)
                {
                    if (string.IsNullOrWhiteSpace(line))
                    {
                        continue;
                    }

                    if (firstLine)
                    {
                        firstLine = false;

                        if (char.IsDigit(line.TrimStart()[0]) == false)
                        {
                            continue;
                        }
                    }

                    var parts = line.Split(new[] { ' ', '\t' },
                        StringSplitOptions.RemoveEmptyEntries);

                    if (parts.Length < 4)
                    {
                        continue;
                    }

                    int d = int.Parse(parts[0], CultureInfo.InvariantCulture);
                    int s = int.Parse(parts[1], CultureInfo.InvariantCulture);
                    uint a = uint.Parse(parts[2], CultureInfo.InvariantCulture);

                    if (parts.Length < 3 + s)
                    {
                        throw new FormatException(
                                                $"Joe-Kuo line for dimension {d} is missing direction numbers.");
                    }

                    if (d != expectedD)
                    {
                        throw new FormatException(
                                                $"Joe-Kuo file: expected dimension {expectedD}, got {d}.");
                    }

                    expectedD++;

                    var m = new uint[s];

                    for (int i = 0; i < s; i++)
                    {
                        m[i] = uint.Parse(parts[3 + i], CultureInfo.InvariantCulture);
                    }

                    list.Add(new Entry(s, a, m));
                }
            }

            if (list.Count <= _builtIn.Length)
            {
                throw new InvalidOperationException(
                                "Loaded Joe-Kuo file does not extend the built-in table.");
            }

            _extended = list.ToArray();
        }

        public static void ResetToBuiltIn() => _extended = null;
